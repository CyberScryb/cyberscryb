/**
 * Emit client-side tools registry from scripts/toolsConfig.js
 * Usage: node scripts/emit-tools-registry.js
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { tools } = require('./toolsConfig');

const root = path.join(__dirname, '..');
const targets = [
  path.join(root, 'content-site', 'tools', 'shared', 'tools-registry.js'),
  path.join(root, 'public', 'tools', 'shared', 'tools-registry.js'),
];

const clientTools = tools.map((t) => ({
  id: t.id,
  slug: t.slug,
  title: t.title,
  chainsTo: (t.chainsTo || []).map((c) => ({
    id: c.id,
    label: c.label,
    toField: c.toField || null,
    map: c.map || null,
  })),
  shareKind: t.shareKind == null ? null : t.shareKind,
  offline: !!t.offline,
  persistPolicy: t.persistPolicy || null,
  shareRequiresConfirm: !!t.shareRequiresConfirm,
  primaryInputId: t.primaryInputId || null,
  primaryOutputId: t.primaryOutputId || null,
}));

const body =
  '// AUTO-GENERATED by scripts/emit-tools-registry.js — do not edit by hand\n' +
  'window.CSToolsRegistry = ' +
  JSON.stringify({ tools: clientTools }, null, 2) +
  ';\n';

for (const file of targets) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body, 'utf8');
  console.log('Wrote', path.relative(root, file));
}

console.log('emit-tools-registry: ok (' + clientTools.length + ' tools)');
